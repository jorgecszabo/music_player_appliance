#!/bin/sh
# Appliance setup, run on the device as root. Idempotent: safe to run again
# after every deploy (scripts/deploy.sh) and from the first-boot script.
# Reads /etc/panda/board.conf and /etc/panda/appliance.conf, generates the
# board-dependent configs, installs packages, creates service users, enables
# services, and saves everything with lbu.
set -eu
. /etc/panda/board.conf
. /etc/panda/appliance.conf

log() { echo "panda-setup: $*"; logger -t panda-setup "$*" 2>/dev/null || true; }

PACKAGES="alsa-utils pipewire pipewire-alsa pipewire-tools wireplumber spotifyd"

# --- Repositories: boot media first, then the online main + community ----------
rel="v$(cut -d. -f1,2 /etc/alpine-release)"
mirror="${ALPINE_MIRROR:-https://dl-cdn.alpinelinux.org/alpine}"
for repo in main community; do
	grep -qx "$mirror/$rel/$repo" /etc/apk/repositories \
		|| echo "$mirror/$rel/$repo" >> /etc/apk/repositories
done

# --- Packages (the apk cache lives on the read-only boot media) ---------------
missing=""
for p in $PACKAGES; do
	apk info -e "$p" >/dev/null 2>&1 || missing="$missing $p"
done
if [ -n "$missing" ]; then
	log "installing:$missing"
	mount -o remount,rw /media/"$BOOT_MEDIA"
	if apk update -q && apk add $missing && apk cache sync; then rc=0; else rc=$?; fi
	sync
	mount -o remount,ro /media/"$BOOT_MEDIA"
	[ "$rc" -eq 0 ] || { log "ERROR: apk add failed"; exit 1; }
fi

# --- Device manager: eudev instead of mdev -----------------------------------------
# PipeWire finds sound cards through libudev. With mdev, eudev's libudev reports
# every device as uninitialized and PipeWire skips them. udev also sets the
# /dev/snd permissions and handles USB hotplug (DAC, BT dongle).
if ! rc-update show sysinit 2>/dev/null | grep -q '^ *udev '; then
	log "switching the device manager to eudev"
	mount -o remount,rw /media/"$BOOT_MEDIA"
	if setup-devd udev && apk cache sync; then rc=0; else rc=$?; fi
	sync
	mount -o remount,ro /media/"$BOOT_MEDIA"
	[ "$rc" -eq 0 ] || { log "ERROR: setup-devd udev failed"; exit 1; }
fi

# --- Service user ---------------------------------------------------------------
if ! id speaker >/dev/null 2>&1; then
	log "creating system user speaker"
	addgroup -S speaker
	adduser -S -D -H -h /var/lib/speaker -s /sbin/nologin -G speaker -g "Audio services" speaker
fi
addgroup speaker audio 2>/dev/null || true

# --- PipeWire: fixed hardware rate from board.conf ------------------------------
mkdir -p /etc/pipewire/pipewire.conf.d
cat > /etc/pipewire/pipewire.conf.d/10-panda.conf <<EOF
# Generated by /etc/panda/setup.sh from board.conf. Don't edit here.
context.properties = {
    # $AUDIO_CARD only runs at $AUDIO_RATE Hz: resample everything to it.
    default.clock.rate          = $AUDIO_RATE
    default.clock.allowed-rates = [ $AUDIO_RATE ]
    # Large buffers: latency doesn't matter on a speaker, dropouts do.
    default.clock.quantum       = 2048
    default.clock.min-quantum   = 1024
    default.clock.max-quantum   = 4096
    # No desktop session bus on the appliance.
    module.portal               = false
    module.jackdbus-detect      = false
    module.x11.bell             = false
}
stream.properties = {
    resample.quality = 4
}
EOF

# --- WirePlumber: embedded profile, only the board's sound card -------------------
mkdir -p /etc/wireplumber/wireplumber.conf.d
cat > /etc/wireplumber/wireplumber.conf.d/10-panda.conf <<EOF
# Generated by /etc/panda/setup.sh from board.conf. Don't edit here.
wireplumber.profiles = {
  panda = {
    inherits = [ main-embedded ]
    hardware.bluetooth = disabled
    hardware.video-capture = disabled
    # No desktop session bus on the appliance (also drops mpris/notifications).
    support.dbus = disabled
  }
}

monitor.alsa.rules = [
  {
    # Only the board's audio output; ignore other cards (e.g. HDMI).
    matches = [ { device.name = "~alsa_card.*", api.alsa.card.name = "!$AUDIO_CARD" } ]
    actions = { update-props = { device.disabled = true } }
  }
  {
    matches = [ { node.name = "~alsa_output.*" } ]
    actions = {
      update-props = {
        audio.rate = $AUDIO_RATE
        audio.channels = $AUDIO_CHANNELS
        # The TWL6040 crackles when the device is open without data (idle),
        # and closing it on idle (suspend) gives crackle during the timeout.
        # So never suspend, and keep the graph running: idle = real silence.
        session.suspend-timeout-seconds = 0
        node.pause-on-idle = false
        # ...and run from boot, even before the first stream connects.
        node.always-process = true
        # Interrupt-driven scheduling: the OMAP4 McPDM/sDMA position is too coarse
        # for timer-based scheduling (about 3 underruns/s = crackle; 0 with IRQs).
        api.alsa.disable-tsched = true
        api.alsa.period-size = 2048
        api.alsa.period-num = 4
      }
    }
  }
]
EOF

# --- Spotify Connect (spotifyd) ---------------------------------------------------
cat > /etc/spotifyd.conf <<EOF
# Generated by /etc/panda/setup.sh from appliance.conf. Don't edit here.
[global]
device_name = "$SPEAKER_NAME"
device_type = "speaker"
# Output into PipeWire through its ALSA plugin.
backend = "alsa"
device = "pipewire"
# Spotify's volume slider drives PipeWire's main (sink) volume. spotifyd 0.4:
# "mixer" is the ALSA control *device*, "control" the volume control name.
volume_controller = "alsa"
mixer = "pipewire"
control = "Master"
bitrate = 320
volume_normalisation = true
# Login comes from the phone through zeroconf; cache in RAM only.
cache_path = "/var/lib/speaker/spotifyd-cache"
max_cache_size = 50000000
# Fixed port so the firewall can allow it.
zeroconf_port = $SPOTIFY_ZEROCONF_PORT
use_mpris = false
EOF
# The package ships it as 0640 root:spotifyd; it holds no secrets.
chmod 0644 /etc/spotifyd.conf

# --- Services -------------------------------------------------------------------
for svc in panda-audio-init speaker-pipewire speaker-wireplumber speaker-spotifyd; do
	rc-update add "$svc" default >/dev/null 2>&1 || true
done

log "done; saving with lbu"
lbu commit
