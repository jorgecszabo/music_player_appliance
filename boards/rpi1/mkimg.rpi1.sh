# Alpine mkimage profile for the Raspberry Pi 1 Model B audio appliance.
# Loaded by aports/scripts/mkimage.sh from ~/.mkimage, where
# scripts/build-image.sh copies it together with board.conf, appliance.conf,
# packages.list, the apkovl generator and panda-keys.dts. The output tarball is
# unpacked onto the SD card's FAT partition (boards/rpi1/write-sdcard.sh).
#
# Boot: the GPU firmware (bootcode.bin, start.elf) reads config.txt, which
# includes slot.txt: os_prefix=slots/<x>/ plus the kernel and initramfs lines.
# The firmware then loads the kernel, initramfs, cmdline.txt, the DTB and the
# overlays from that slot. panda-ota.py (scheme "rpi") writes slot.txt and each
# slot's cmdline.txt from the slot's extlinux.label, which this profile
# generates like the other boards' (no bootloader reads it). update-kernel puts
# an rpi flavor's DTBs and overlays/ in the root; build-image.sh moves them
# into slot a.

rpi1_extlinux_gen() {
	cat <<-EOF
	# Generated by mkimg.rpi1.sh
	DEFAULT $KERNEL_FLAVOR
	TIMEOUT 10
	LABEL $KERNEL_FLAVOR
	MENU LABEL Alpine Linux ($KERNEL_FLAVOR)
	KERNEL /boot/vmlinuz-$KERNEL_FLAVOR
	INITRD /boot/initramfs-$KERNEL_FLAVOR
	APPEND $initfs_cmdline $kernel_cmdline
	EOF
}

rpi1_config_gen() {
	cat <<-EOF
	# Generated by mkimg.rpi1.sh (GPU firmware settings). Outside the OTA slots:
	# an update doesn't change it. Local changes go in usercfg.txt.
	# slot.txt (panda-ota.py): os_prefix=slots/<x>/, kernel=, initramfs.
	include slot.txt
	enable_uart=1
	disable_splash=1
	gpu_mem=$RPI_GPU_MEM
	# Overclock (board.conf; RPI1.md S1).
	arm_freq=$RPI_ARM_FREQ
	core_freq=$RPI_CORE_FREQ
	sdram_freq=$RPI_SDRAM_FREQ
	over_voltage=$RPI_OVER_VOLTAGE
	# The 3.5 mm jack (snd_bcm2835).
	dtparam=audio=on
	# The 2.8" TFT: ILI9341 (fbtft, landscape, 32 MHz, 25 fps) + STMPE610 touch
	# and backlight; the 4 buttons.
	dtparam=spi=on
	dtoverlay=pitft28-resistive
	dtoverlay=panda-keys
	include usercfg.txt
	EOF
}

build_rpi1_extlinux() {
	mkdir -p "$DESTDIR"/extlinux
	rpi1_extlinux_gen > "$DESTDIR"/extlinux/extlinux.conf
}

section_rpi1_extlinux() {
	[ -n "$rpi1_extlinux" ] || return 0
	build_section rpi1_extlinux $(rpi1_extlinux_gen | checksum)
}

build_rpi1_config() {
	rpi1_config_gen > "$DESTDIR"/config.txt
	: > "$DESTDIR"/usercfg.txt
	mkdir -p "$DESTDIR"/overlays
	dtc -@ -q -I dts -O dtb -o "$DESTDIR"/overlays/panda-keys.dtbo "$HOME"/.mkimage/panda-keys.dts
}

section_rpi1_config() {
	[ -n "$rpi1_extlinux" ] || return 0
	build_section rpi1_config $( (rpi1_config_gen; cat "$HOME"/.mkimage/panda-keys.dts) | checksum)
	# bootcode.bin, start.elf, fixup.dat (mkimg.arm.sh).
	build_section rpi_blobs
}

profile_rpi1() {
	profile_base
	. "$HOME"/.mkimage/board.conf
	. "$HOME"/.mkimage/appliance.conf
	title="$BOARD_NAME"
	desc="Diskless Alpine for the $BOARD_NAME audio appliance."
	image_ext="tar.gz"
	arch="$ALPINE_ARCH"
	kernel_flavors="$KERNEL_FLAVOR"
	kernel_addons=
	initfs_features="base mmc squashfs usb"
	# No "quiet": the boot log on serial is the main debugging tool.
	initfs_cmdline="modules=loop,squashfs,sd-mod,usb-storage"
	# Serial, then tty1 last (it is /dev/console, so OpenRC's output goes there
	# too). fbcon=map:1 puts the text consoles on the TFT (fb1): the boot log is
	# the panel's "POST" screen until panda-lcd takes the framebuffer over.
	kernel_cmdline="console=$CONSOLE console=tty1 fbcon=map:1 consoleblank=0"
	modloopfw="$MODLOOP_EXTRA_FIRMWARE"
	rpi1_extlinux=yes
	# The GPU firmware boots Linux; no GRUB/EFI (profile_base enables it for ARM).
	grub_mod=
	# The appliance (panda-appliance depends on packages.list) and its board.
	apks="$(sed 's/#.*//' "$HOME"/.mkimage/packages.list) $BOARD_PACKAGES panda-appliance panda-board-$BOARD"
	apkovl="genapkovl.sh"
	hostname="$HOSTNAME"
}
