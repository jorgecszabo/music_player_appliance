#!/bin/sh
# Generate every config file that depends on board.conf / appliance.conf /
# audio.conf: PipeWire, the tone filter, WirePlumber, shairport-sync, bluez,
# the watchdog. Board-independent: hardware quirks come from board.conf.
#
#   gen-configs.sh                      on the device (setup.sh runs it)
#   CONF_DIR=dir ROOT=out gen-configs.sh  anywhere, e.g. on the build host to
#                                       check a new board.conf (writes under out/)
#
# CONF_DIR holds board.conf, appliance.conf and (optional) audio.conf.
set -eu
CONF_DIR="${CONF_DIR:-/etc/panda}"
ROOT="${ROOT:-}"
HERE="$(dirname "$(readlink -f "$0")")"
. "$CONF_DIR"/board.conf
. "$CONF_DIR"/appliance.conf
[ -f "$CONF_DIR"/audio.conf ] && . "$CONF_DIR"/audio.conf

# --- Defaults for boards that don't set these --------------------------------------
# Graph quantum (frames). Big = robust; latency doesn't matter for a speaker.
AUDIO_QUANTUM="${AUDIO_QUANTUM:-1024}"
AUDIO_MIN_QUANTUM="${AUDIO_MIN_QUANTUM:-$((AUDIO_QUANTUM / 2))}"
AUDIO_MAX_QUANTUM="${AUDIO_MAX_QUANTUM:-$((AUDIO_QUANTUM * 2))}"
# Extra WirePlumber properties for the ALSA output node (codec quirks), one per line.
AUDIO_OUTPUT_PROPS="${AUDIO_OUTPUT_PROPS:-}"
# Bluetooth: "dual" (BR/EDR + LE) unless the controller is classic only.
BT_CONTROLLER_MODE="${BT_CONTROLLER_MODE:-dual}"
# A2DP receive jitter buffer (samples at 44.1/48 kHz); 8192 = about 186 ms.
BT_RX_BUFFER="${BT_RX_BUFFER:-8192}"
WATCHDOG_TIMEOUT="${WATCHDOG_TIMEOUT:-60}"

GEN="# Generated by /etc/panda/gen-configs.sh from board.conf/appliance.conf. Don't edit here."
out() { mkdir -p "$(dirname "$ROOT$1")"; cat > "$ROOT$1"; }

# --- PipeWire ---------------------------------------------------------------------------
if [ -n "${AUDIO_RATE:-}" ]; then
	rates="    # $AUDIO_CARD only runs at $AUDIO_RATE Hz: resample everything to it.
    default.clock.rate          = $AUDIO_RATE
    default.clock.allowed-rates = [ $AUDIO_RATE ]"
else
	rates="    default.clock.allowed-rates = [ 44100 48000 ]"
fi
out /etc/pipewire/pipewire.conf.d/10-panda.conf <<EOF
$GEN
context.properties = {
$rates
    # Large buffers: latency doesn't matter on a speaker, dropouts do.
    default.clock.quantum       = $AUDIO_QUANTUM
    default.clock.min-quantum   = $AUDIO_MIN_QUANTUM
    default.clock.max-quantum   = $AUDIO_MAX_QUANTUM
    # No desktop session bus on the appliance.
    module.portal               = false
    module.jackdbus-detect      = false
    module.x11.bell             = false
}
stream.properties = {
    resample.quality = 4
}
EOF

# Tone filter (bass/treble/headroom), from audio.conf.
CONF_DIR="$CONF_DIR" sh "$HERE"/tone-conf.sh | out /etc/pipewire/pipewire.conf.d/20-panda-tone.conf

# --- WirePlumber ----------------------------------------------------------------------
output_props=""
if [ -n "$AUDIO_OUTPUT_PROPS" ]; then
	output_props=$(printf '%s\n' "$AUDIO_OUTPUT_PROPS" | sed 's/^/        /')
fi
out /etc/wireplumber/wireplumber.conf.d/10-panda.conf <<EOF
$GEN
wireplumber.profiles = {
  panda = {
    inherits = [ main-embedded ]
    # Bluetooth A2DP sink. ("optional" means "only if another feature wants
    # it", so it wouldn't load. The monitor just waits if bluez is absent.)
    hardware.bluetooth = required
    monitor.bluez-midi = disabled
    hardware.video-capture = disabled
    # No desktop session bus on the appliance (also drops mpris/notifications).
    support.dbus = disabled
  }
}

# Startup volume: the output at 100% (0 dB) on every boot. The hardware gain
# (board.conf AUDIO_HW_VOLUME_*, audio.conf MAX_VOLUME) is the loudness cap;
# each source controls its own stream volume. WirePlumber's state is in RAM.
wireplumber.settings = {
  device.routes.default-sink-volume = 1.0
  node.stream.default-playback-volume = 1.0
  # A speaker: no headset/mic profile, and nothing remembered across reboots.
  bluetooth.autoswitch-to-headset-profile = false
  bluetooth.use-persistent-storage = false
}

# Bluetooth: act as an A2DP sink only (no HFP/HSP: there's no microphone).
# The phone's volume (AVRCP absolute volume) drives the BT stream's volume.
monitor.bluez.properties = {
  bluez5.roles = [ a2dp_sink ]
  bluez5.codecs = [ sbc sbc_xq aac ]
  bluez5.hfphsp-backend = "none"
  bluez5.hw-volume = [ a2dp_sink ]
}

# Receive side (phone -> us): a fixed jitter buffer. The automatic one starts at
# about one quantum and only grows after it has seen a delay spike (forgetting
# it after 2 min), which gave occasional skips. Costs video lip-sync on the phone.
monitor.bluez.rules = [
  {
    matches = [ { node.name = "~bluez_input.*" } ]
    actions = { update-props = { bluez5.decode-buffer.latency = $BT_RX_BUFFER } }
  }
]

monitor.alsa.rules = [
  {
    # Only the board's audio output; ignore other cards (e.g. HDMI).
    matches = [ { device.name = "~alsa_card.*", api.alsa.card.name = "!$AUDIO_CARD" } ]
    actions = { update-props = { device.disabled = true } }
  }
  {
    # Volume in software only. Otherwise ACP may map the output volume onto the
    # codec's hardware gain, and the hardware gain could never be a cap.
    matches = [ { device.name = "~alsa_card.*", api.alsa.card.name = "$AUDIO_CARD" } ]
    actions = { update-props = { api.alsa.soft-mixer = true } }
  }
  {
    matches = [ { node.name = "~alsa_output.*" } ]
    actions = {
      update-props = {
        ${AUDIO_RATE:+audio.rate = $AUDIO_RATE}
        audio.channels = ${AUDIO_CHANNELS:-2}
        # Board quirks (board.conf AUDIO_OUTPUT_PROPS):
$output_props
      }
    }
  }
]
EOF

# --- AirPlay (classic): shairport-sync ---------------------------------------------------
out /etc/shairport-sync.conf <<EOF
// Generated by /etc/panda/gen-configs.sh from appliance.conf. Don't edit here.
general = {
	name = "$SPEAKER_NAME";
	// Native PipeWire backend (our aports/shairport-sync build; Alpine's lacks
	// it). Avoids the pipewire-alsa plugin and its jittery delay reports.
	output_backend = "pipewire";
	mdns_backend = "avahi";
	interpolation = "basic";
};
sessioncontrol = {
	// A guest's iPhone can take over from another AirPlay sender.
	allow_session_interruption = "yes";
};
pipewire = {
	application_name = "AirPlay";
	node_name = "airplay";
};
// Track info for the web page (read by panda-arbiter).
metadata = {
	enabled = "yes";
	include_cover_art = "no";
	pipe_name = "/run/speaker/shairport-metadata";
	pipe_timeout = 5000;
};
EOF

# --- Bluetooth: bluez ---------------------------------------------------------------------
out /etc/bluetooth/main.conf <<EOF
$GEN
[General]
Name = $SPEAKER_NAME
# Audio + Rendering service, Audio/Video major class, Loudspeaker.
Class = 0x240414
# board.conf BT_CONTROLLER_MODE (A2DP is classic BT; "bredr" for BR/EDR-only chips).
ControllerMode = $BT_CONTROLLER_MODE
# Discoverable/pairable only while panda-bt opens the pairing window.
DiscoverableTimeout = 120
PairableTimeout = 120
AlwaysPairable = false
# Re-pairing a known phone (it forgot us) goes through the agent's window check.
JustWorksRepairing = confirm
FastConnectable = true

[Policy]
AutoEnable = true
ReconnectAttempts = 7
ReconnectIntervals = 1,2,4,8,16,32,64
EOF

# --- Watchdog: busybox watchdog pets the board's hardware watchdog -------------------------
out /etc/conf.d/watchdog <<EOF
$GEN
WATCHDOG_DEV="${WATCHDOG_DEV:-/dev/watchdog}"
# -T: hardware timeout (s), -t: pet interval (s).
WATCHDOG_OPTS="-T $WATCHDOG_TIMEOUT -t $((WATCHDOG_TIMEOUT / 6))"
EOF
