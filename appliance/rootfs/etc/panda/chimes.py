#!/usr/bin/env python3
"""Synthesize the appliance's chimes (short bell tones, no speech) as WAVs.

Usage: chimes.py <outdir>    writes <event>.wav for every event below.
Stdlib only. Output: 48 kHz mono 16-bit, peak at -6 dBFS (the playback level
is set by chime.sh). Generated by setup.sh onto the boot media (read-only at runtime).
"""
import math
import os
import struct
import sys
import wave

RATE = 48000

# Note frequencies (equal temperament, A4 = 440 Hz).
def note(name):
    names = {"C": -9, "D": -7, "E": -5, "F": -4, "G": -2, "A": 0, "B": 2}
    semis = names[name[0]] + (1 if "#" in name else 0) + 12 * (int(name[-1]) - 4)
    return 440.0 * 2 ** (semis / 12)

# event: list of (note, start_s, decay_s, gain)
CHIMES = {
    "boot":         [("C5", 0.00, 0.50, 0.8), ("G5", 0.18, 0.50, 0.8),
                     ("C6", 0.36, 0.55, 0.8), ("E6", 0.54, 0.90, 0.9)],
    "pairing-on":   [("E6", 0.00, 0.18, 0.7), ("E6", 0.16, 0.18, 0.7), ("E6", 0.32, 0.35, 0.8)],
    "paired":       [("C6", 0.00, 0.30, 0.8), ("E6", 0.10, 0.30, 0.8), ("G6", 0.20, 0.70, 0.9)],
    "connected":    [("G5", 0.00, 0.35, 0.8), ("C6", 0.14, 0.70, 0.9)],
    "disconnected": [("C6", 0.00, 0.35, 0.8), ("G5", 0.14, 0.70, 0.9)],
    "pairing-off":  [("G5", 0.00, 0.35, 0.6), ("D5", 0.16, 0.70, 0.7)],
    "forgot-all":   [("G5", 0.00, 0.35, 0.8), ("E5", 0.18, 0.35, 0.8), ("C5", 0.36, 0.90, 0.9)],
}

# Bell-ish timbre: partials (ratio, relative gain, decay multiplier).
PARTIALS = [(1.0, 1.0, 1.0), (2.0, 0.35, 0.5), (3.0, 0.12, 0.33), (4.2, 0.05, 0.25)]
ATTACK_S = 0.004


def render(notes):
    end = max(start + decay * 3.5 for _, start, decay, _ in notes)
    n = int(end * RATE)
    buf = [0.0] * n
    for name, start, decay, gain in notes:
        f0 = note(name)
        s0 = int(start * RATE)
        length = min(n - s0, int(decay * 3.5 * RATE))
        for ratio, pg, dm in PARTIALS:
            f = f0 * ratio
            if f > RATE / 2.5:
                continue
            w = 2 * math.pi * f / RATE
            k = 1.0 / (decay * dm * RATE)   # exponential decay per sample
            amp = gain * pg
            for i in range(length):
                env = math.exp(-i * k)
                if i < ATTACK_S * RATE:
                    env *= i / (ATTACK_S * RATE)
                buf[s0 + i] += amp * env * math.sin(w * i)
    # Fade the tail to zero and normalize to -6 dBFS.
    fade = int(0.02 * RATE)
    for i in range(fade):
        buf[n - 1 - i] *= i / fade
    peak = max(abs(x) for x in buf) or 1.0
    scale = 0.5 * 32767 / peak
    return b"".join(struct.pack("<h", int(x * scale)) for x in buf)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for event, notes in CHIMES.items():
        tmp = os.path.join(out, f".{event}.wav")
        with wave.open(tmp, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(render(notes))
        os.replace(tmp, os.path.join(out, f"{event}.wav"))


if __name__ == "__main__":
    main()
