#!/bin/sh
# Print the PipeWire filter-chain config for the tone filter ("panda-eq"), from
# /etc/panda/audio.conf and board.conf. Used by setup.sh (boot values); the web
# page changes the running filter live (web-admin.sh set-audio).
#
# Graph per channel: preamp (headroom) -> bass low shelf -> treble high shelf.
# Headroom = 3 dB (resampler intersample overs, measured on AirPlay) plus any
# bass/treble boost, so boosting can't clip.
CONF_DIR="${CONF_DIR:-/etc/panda}"
. "$CONF_DIR"/board.conf
[ -f "$CONF_DIR"/audio.conf ] && . "$CONF_DIR"/audio.conf
mult=$(awk -v b="${BASS_DB:-0}" -v t="${TREBLE_DB:-0}" 'BEGIN {
	m = b; if (t > m) m = t; if (m < 0) m = 0
	printf "%.6f", 10 ^ (-(3 + m) / 20) }')
cat <<CONF
# Generated by /etc/panda/tone-conf.sh from audio.conf. Don't edit here.
context.modules = [
  { name = libpipewire-module-filter-chain
    args = {
      node.description = "Speaker (tone)"
      media.name = "Speaker (tone)"
      filter.graph = {
        nodes = [
          { type = builtin name = pre    label = linear       control = { "Mult" = $mult } }
          { type = builtin name = bass   label = bq_lowshelf  control = { "Freq" = 100.0  "Q" = 0.707 "Gain" = ${BASS_DB:-0}.0 } }
          { type = builtin name = treble label = bq_highshelf control = { "Freq" = 8000.0 "Q" = 0.707 "Gain" = ${TREBLE_DB:-0}.0 } }
        ]
        links = [
          { output = "pre:Out"  input = "bass:In" }
          { output = "bass:Out" input = "treble:In" }
        ]
      }
      audio.channels = ${AUDIO_CHANNELS:-2}
      audio.position = [ FL FR ]
      capture.props = {
        node.name = "panda-eq"
        media.class = Audio/Sink
        # The default sink: every source plays through the filter.
        priority.session = 2000
      }
      playback.props = {
        node.name = "panda-eq.output"
        node.passive = true
        target.object = "${AUDIO_PW_SINK}"
        stream.dont-remix = true
      }
    }
  }
]
CONF
