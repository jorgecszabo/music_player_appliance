#!/bin/bash
# Build the static demo of the web control panel: docs/panel-demo.html, one
# self-contained file (the real index.html, style.css and app.js, plus the fake
# API in docs/demo/mock.js), and the README screenshot docs/panel-demo.png.
# Rerun after changing the web page. Needs python3; the screenshot needs chromium.
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WEB="$PROJECT_DIR/appliance/rootfs/etc/panda/web"
OUT="$PROJECT_DIR/docs/panel-demo.html"

python3 -I - "$WEB" "$PROJECT_DIR/docs/demo/mock.js" "$OUT" <<'EOF'
import sys, pathlib
web, mock, out = map(pathlib.Path, sys.argv[1:])
html = (web / "index.html").read_text()
css, js, fake = (web / "style.css").read_text(), (web / "app.js").read_text(), mock.read_text()
for src in (js, fake):
    assert "</script" not in src.lower(), "can't inline a script containing </script"
def swap(old, new):
    global html
    assert html.count(old) == 1, f"index.html: expected one {old!r}"
    html = html.replace(old, new)
swap('<link rel="stylesheet" href="style.css">', f"<style>\n{css}</style>")
# The fake API goes first; app.js last (it was deferred: it needs the whole page).
swap('<script src="app.js" defer></script>', f"<script>\n{fake}</script>")
swap("</body>", f"<script>\n{js}</script>\n</body>")
out.write_text("<!-- Generated by scripts/build-demo.sh: edit appliance/rootfs/etc/panda/web/ and docs/demo/mock.js instead. -->\n" + html)
EOF
echo "wrote ${OUT#"$PROJECT_DIR/"}"

browser=$(command -v chromium-browser chromium google-chrome 2>/dev/null | head -1 || true)
if [ -n "$browser" ]; then
    "$browser" --headless --disable-gpu --hide-scrollbars --window-size=1024,900 \
        --virtual-time-budget=4000 --screenshot="$PROJECT_DIR/docs/panel-demo.png" \
        "file://$OUT" 2>/dev/null
    echo "wrote docs/panel-demo.png"
else
    echo "no chromium: screenshot not updated" >&2
fi
