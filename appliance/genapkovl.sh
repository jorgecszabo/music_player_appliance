#!/bin/sh -e
# First-boot overlay (apkovl) for the appliance image. Board-independent: reads
# board.conf and appliance.conf from its own directory (scripts/build-image.sh
# copies them next to it in ~/.mkimage) and installs both as /etc/panda/*.conf.
#
# Settings only: the appliance's code comes from the panda-appliance package
# (world: panda-appliance panda-board-<board>), so an OTA update can replace it
# (files in the overlay win over package files at boot). Sets up: hostname,
# DHCP on eth0, chrony, avahi, SSH (key-only, admin user only), doas,
# appliance.conf, the services, and optional extra settings files (rootfs.tar
# next to this script: the factory Wi-Fi). At boot, panda-setup (from the
# package) generates the configs and creates the service users; a first-boot
# script creates the admin user. This overlay is also the factory copy.
# The SSH keys come from appliance/authorized_keys (generated by
# scripts/build-image.sh from the build host's ~/.ssh/*.pub; not in git).
HERE="$(dirname "$(readlink -f "$0")")"
. "$HERE"/board.conf
. "$HERE"/appliance.conf
KEYS="$HERE/authorized_keys"
HOST="${1:-$HOSTNAME}"
[ -n "$HOST" ] || { echo "usage: $0 hostname"; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

makefile() {
	OWNER="$1"; PERMS="$2"; FILENAME="$3"
	cat > "$FILENAME"
	chown "$OWNER" "$FILENAME"
	chmod "$PERMS" "$FILENAME"
}

rc_add() {
	mkdir -p "$tmp"/etc/runlevels/"$2"
	ln -sf /etc/init.d/"$1" "$tmp"/etc/runlevels/"$2"/"$1"
}

mkdir -p "$tmp"/etc/network "$tmp"/etc/apk \
	"$tmp"/etc/apk/protected_paths.d "$tmp"/etc/ssh/sshd_config.d \
	"$tmp"/etc/doas.d "$tmp"/etc/local.d "$tmp"/etc/panda

# Extra settings files (scripts/build-image.sh: the factory Wi-Fi).
if [ -f "$HERE"/rootfs.tar ]; then
	tar -x -C "$tmp" -f "$HERE"/rootfs.tar
fi

# Appliance identity (the speaker name is changed on the web page). board.conf
# comes with panda-board-<board>.
makefile root:root 0644 "$tmp"/etc/panda/appliance.conf < "$HERE"/appliance.conf

makefile root:root 0644 "$tmp"/etc/hostname <<EOT
$HOST
EOT

makefile root:root 0644 "$tmp"/etc/network/interfaces <<EOT
auto lo
iface lo inet loopback

auto eth0
iface eth0 inet dhcp
EOT

makefile root:root 0644 "$tmp"/etc/apk/world <<EOT
alpine-base
panda-appliance
panda-board-$BOARD
!mesa
!libcamera
EOT

# SSH: key-only, only the admin user. Root keeps its password for the serial
# console (recovery).
makefile root:root 0644 "$tmp"/etc/ssh/sshd_config.d/panda.conf <<EOT
PermitRootLogin no
AllowUsers $ADMIN_USER
PasswordAuthentication no
KbdInteractiveAuthentication no
EOT

# Admin user gets root through doas without a password (key-only SSH is the gate).
# Not in "wheel": the stock doas.conf has a password rule for :wheel, and the last
# matching rule wins.
makefile root:root 0600 "$tmp"/etc/doas.d/panda.conf <<EOT
permit nopass $ADMIN_USER
EOT

if [ -s "$KEYS" ]; then
	makefile root:root 0644 "$tmp"/etc/panda/authorized_keys < "$KEYS"
else
	echo "WARNING: no $KEYS; add a key for $ADMIN_USER on the board" >&2
fi

# First boot: create the admin user, install its keys, save. (panda-setup has
# set up lbu and the appliance earlier in this boot.)
# Runs on the device; it reads its settings from /etc/panda/*.conf.
makefile root:root 0755 "$tmp"/etc/local.d/panda-firstboot.start <<'EOT'
#!/bin/sh
# Runs from the "local" service on every boot; does nothing once the admin
# user exists.
. /etc/panda/board.conf
. /etc/panda/appliance.conf
id "$ADMIN_USER" >/dev/null 2>&1 && exit 0
logger -t panda-firstboot "creating admin user $ADMIN_USER"
adduser -D -s /bin/ash -g "Appliance admin" "$ADMIN_USER"
# adduser -D locks the account ("!"), and OpenSSH refuses key logins to locked
# accounts. "*" = no password, but not locked.
echo "$ADMIN_USER:*" | chpasswd -e
install -d -o "$ADMIN_USER" -g "$ADMIN_USER" -m 0700 /home/"$ADMIN_USER"/.ssh
if [ -s /etc/panda/authorized_keys ]; then
	install -o "$ADMIN_USER" -g "$ADMIN_USER" -m 0600 /etc/panda/authorized_keys \
		/home/"$ADMIN_USER"/.ssh/authorized_keys
fi
if mkdir -p /run/panda && flock /run/panda/media.lock lbu commit; then
	logger -t panda-firstboot "saved with lbu"
else
	logger -t panda-firstboot "ERROR: lbu commit failed"
fi
EOT

# lbu saves /etc by default; also save the admin user's SSH keys.
makefile root:root 0644 "$tmp"/etc/apk/protected_paths.d/lbu.list <<EOT
+home/$ADMIN_USER/.ssh
EOT

rc_add devfs sysinit
rc_add dmesg sysinit
# eudev instead of mdev: PipeWire finds sound cards through libudev.
rc_add udev sysinit
rc_add udev-trigger sysinit
rc_add udev-settle sysinit
rc_add modloop sysinit

rc_add hwclock boot
rc_add modules boot
rc_add sysctl boot
rc_add hostname boot
rc_add bootmisc boot
rc_add syslog boot
rc_add networking boot
rc_add panda-ota-boot boot
rc_add panda-setup boot
rc_add panda-firewall boot
rc_add panda-reset-button boot

rc_add chronyd default
rc_add dbus default
rc_add avahi-daemon default
rc_add sshd default
rc_add local default
rc_add udev-postmount default
rc_add crond default
for s in panda-audio-init speaker-pipewire speaker-wireplumber speaker-soloist \
	speaker-shairport speaker-radio speaker-arbiter panda-radio-init bluetooth panda-bt \
	panda-wifi panda-chime-boot panda-web panda-ota-confirm; do
	rc_add "$s" default
done

rc_add mount-ro shutdown
rc_add killprocs shutdown
rc_add savecache shutdown

tar -c -C "$tmp" --owner=0 --group=0 etc | gzip -9n > "$HOST".apkovl.tar.gz
